package com.expenseflow.seed;

import java.time.Instant;
import java.util.List;
import java.util.Map;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/** Renders docs/testing/seed-summary.md from what is actually in the database. */
@Component
public class SeedSummary {

    private final JdbcTemplate jdbc;

    public SeedSummary(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    private long count(String sql, Object... args) {
        Long n = jdbc.queryForObject(sql, Long.class, args);
        return n == null ? 0 : n;
    }

    private void table(StringBuilder sb, String title, String sql, String... headers) {
        sb.append("\n## ").append(title).append("\n\n| ").append(String.join(" | ", headers)).append(" |\n|");
        for (int i = 0; i < headers.length; i++) sb.append("---|");
        sb.append('\n');
        for (Map<String, Object> row : jdbc.queryForList(sql)) {
            sb.append("| ");
            sb.append(String.join(" | ", row.values().stream().map(v -> v == null ? "-" : v.toString()).toList()));
            sb.append(" |\n");
        }
    }

    public String markdown(long seedMillis) {
        long claims = count("select count(*) from claims");
        long last24 = count("select count(*) from claims where coalesce(submitted_at, created_at) >= now() - interval '24 hours'");
        long last2 = count("select count(*) from claims where coalesce(submitted_at, created_at) >= now() - interval '2 hours'");
        StringBuilder sb = new StringBuilder();
        sb.append("# Seed summary\n\n");
        sb.append("Generated by `SeedSummary` from the seeded database (profile `seed`, Datafaker seed 42, dates relative to the seed time). ")
          .append("Re-generate: run the backend with `SPRING_PROFILES_ACTIVE=seed` on an empty database.\n\n");
        sb.append("| Item | Value |\n|---|---|\n");
        sb.append("| Seeded at (UTC) | ").append(Instant.now().toString(), 0, 16).append(" |\n");
        sb.append("| Seeding time | ").append(seedMillis).append(" ms |\n");
        sb.append("| Departments | ").append(count("select count(*) from departments")).append(" |\n");
        sb.append("| Users | ").append(count("select count(*) from users")).append(" |\n");
        sb.append("| Claims | ").append(claims).append(" |\n");
        sb.append("| Claim lines | ").append(count("select count(*) from claim_lines")).append(" |\n");
        sb.append("| Receipts | ").append(count("select count(*) from receipts")).append(" |\n");
        sb.append("| Approval steps | ").append(count("select count(*) from approval_steps")).append(" |\n");
        sb.append("| Payout batches | ").append(count("select count(*) from payout_batches")).append(" |\n");
        sb.append("| Claims in last 24 h | ").append(last24).append(" (").append(String.format("%.1f", 100.0 * last24 / Math.max(1, claims))).append("%) |\n");
        sb.append("| Claims in last 2 h | ").append(last2).append(" |\n");
        sb.append("| Pending approvals older than 48 h | ")
          .append(count("select count(*) from approval_steps where decision is null and created_at < now() - interval '48 hours'")).append(" |\n");
        sb.append("| Sample audit pending | ").append(count("select count(*) from claims where sample_audit = 'PENDING'")).append(" |\n");

        table(sb, "Claims per status", "select status, count(*) as claims, round(100.0 * count(*) / (select count(*) from claims), 1) as pct "
                + "from claims group by status order by count(*) desc", "Status", "Claims", "%");
        table(sb, "Policy outcome of submitted claims", "select coalesce(policy_outcome, '(draft)') as outcome, count(*) from claims group by 1 order by 2 desc",
                "Outcome", "Claims");
        table(sb, "Lines per policy rule (violations)", "select v->>'code' as rule, v->>'action' as action, count(*) as lines "
                + "from claim_lines l, jsonb_array_elements(l.violations) v group by 1, 2 order by 3 desc", "Rule", "Action", "Lines");
        table(sb, "Claims and spend per department", "select d.name as department, count(distinct u.id) as users, count(c.id) as claims, "
                + "coalesce(sum(c.total_amount), 0) as total_inr from departments d left join users u on u.department_id = d.id "
                + "left join claims c on c.employee_id = u.id group by d.name order by d.name", "Department", "Users", "Claims", "Total INR");
        table(sb, "Users per role", "select role_code, count(*) from user_roles group by 1 order by 2 desc", "Role", "Users");
        table(sb, "Demo claims (employee@expenseflow.test)", "select c.code, c.title, c.status, c.policy_outcome, c.total_amount "
                + "from claims c where c.code like 'DEMO-%' order by c.code", "Code", "Title", "Status", "Outcome", "Total INR");
        table(sb, "Boundary records", "select c.title, c.status, c.policy_outcome from claims c where c.title like 'Boundary check:%' order by c.title",
                "Record", "Status", "Outcome");

        List<Map<String, Object>> logins = jdbc.queryForList("select u.email, string_agg(r.role_code, ', ' order by r.role_code) as roles "
                + "from users u join user_roles r on r.user_id = u.id where u.email in ('employee@expenseflow.test','manager@expenseflow.test',"
                + "'auditor@expenseflow.test','head@expenseflow.test','admin@expenseflow.test','manager2@expenseflow.test') group by u.email order by u.email");
        sb.append("\n## Demo logins (password for all: `Demo@123`, synthetic)\n\n| Email | Roles |\n|---|---|\n");
        for (Map<String, Object> l : logins) sb.append("| ").append(l.get("email")).append(" | ").append(l.get("roles")).append(" |\n");
        return sb.toString();
    }
}
